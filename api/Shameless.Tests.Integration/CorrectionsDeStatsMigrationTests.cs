using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Migrations;
using Npgsql;
using Shameless.Infrastructure.Data;
using Shameless.Tests.Integration.Infrastructure;

namespace Shameless.Tests.Integration;

/// <summary>
/// Une base qui a servi une ancienne version du projet peut déjà porter la table
/// <c>corrections_de_stats</c> : la migration ne doit pas échouer dessus.
/// </summary>
public class CorrectionsDeStatsMigrationTests(ApiFactory factory) : IAsyncLifetime
{
    private const string Migration = "CorrectionsDeStats";

    private static CancellationToken Ct => TestContext.Current.CancellationToken;

    private readonly string _connectionString = new NpgsqlConnectionStringBuilder(factory.ConnectionString)
    {
        Database = $"mig_{Guid.NewGuid():N}"
    }.ConnectionString;

    private AppDbContext _db = null!;

    public async ValueTask InitializeAsync()
    {
        _db = factory.CreateDbContext(_connectionString);
        var previous = _db.Database.GetMigrations().TakeWhile(m => !m.EndsWith($"_{Migration}")).Last();
        await _db.GetService<IMigrator>().MigrateAsync(previous, Ct);
    }

    public async ValueTask DisposeAsync()
    {
        await _db.Database.EnsureDeletedAsync();
        await _db.DisposeAsync();
    }

    [Fact]
    public async Task La_migration_passe_quand_la_table_existe_deja()
    {
        await _db.Database.ExecuteSqlRawAsync("""
            CREATE TABLE corrections_de_stats (
                id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                custom_game_participant_id integer NOT NULL,
                champ character varying(30) NOT NULL,
                valeur character varying(60) NOT NULL);
            CREATE UNIQUE INDEX ix_corrections_de_stats_custom_game_participant_id_champ
                ON corrections_de_stats (custom_game_participant_id, champ);
            """, Ct);

        await _db.GetService<IMigrator>().MigrateAsync(cancellationToken: Ct);

        Assert.True(await TableExisteAsync());
    }

    [Fact]
    public async Task La_migration_cree_la_table_sur_une_base_qui_ne_l_a_pas()
    {
        Assert.False(await TableExisteAsync());

        await _db.GetService<IMigrator>().MigrateAsync(cancellationToken: Ct);

        Assert.True(await TableExisteAsync());
    }

    private async Task<bool> TableExisteAsync()
    {
        var connection = _db.Database.GetDbConnection();
        await connection.OpenAsync(Ct);
        await using var command = connection.CreateCommand();
        command.CommandText = "SELECT count(*) FROM information_schema.tables WHERE table_name = 'corrections_de_stats'";
        var count = (long)(await command.ExecuteScalarAsync(Ct))!;
        await connection.CloseAsync();
        return count == 1;
    }
}
