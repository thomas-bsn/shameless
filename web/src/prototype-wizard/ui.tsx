import { Check, Eye, EyeOff, Copy } from "lucide-react";
import { useState, type ReactNode } from "react";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { cn } from "@/lib/utils";

export function Field({
  id, label, hint, error, secret, value, onChange, onBlur, placeholder, mono = true, autoGenerated,
}: {
  id: string; label: string; hint?: ReactNode; error?: string; secret?: boolean; value: string;
  onChange: (v: string) => void; onBlur?: () => void; placeholder?: string; mono?: boolean; autoGenerated?: boolean;
}) {
  const [shown, setShown] = useState(false);
  return (
    <div className="space-y-1.5">
      <Label htmlFor={id}>{label}</Label>
      <div className="relative">
        <Input
          id={id}
          type={secret && !shown ? "password" : "text"}
          autoComplete="off"
          spellCheck={false}
          value={value}
          placeholder={placeholder}
          aria-invalid={!!error}
          aria-describedby={error ? `${id}-err` : undefined}
          onChange={(e) => onChange(e.target.value)}
          onBlur={onBlur}
          className={cn(mono && "font-mono", secret && "pr-10")}
        />
        {secret && (
          <button
            type="button"
            onClick={() => setShown((s) => !s)}
            className="absolute inset-y-0 right-0 flex w-10 items-center justify-center text-muted-foreground hover:text-foreground"
            aria-label={shown ? "Masquer" : "Afficher"}
          >
            {shown ? <EyeOff className="size-4" /> : <Eye className="size-4" />}
          </button>
        )}
      </div>
      {hint && !error && <p className="text-xs text-muted-foreground">{hint}</p>}
      {error && <p id={`${id}-err`} role="alert" className="text-xs text-destructive">{error}</p>}
      {autoGenerated && null}
    </div>
  );
}

export function CopyBox({ value, label }: { value: string; label?: string }) {
  const [ok, setOk] = useState(false);
  return (
    <div className="space-y-1">
      {label && <div className="text-xs text-muted-foreground">{label}</div>}
      <div className="flex items-center gap-2 rounded-md border bg-muted/40 px-3 py-2">
        <code className="min-w-0 flex-1 break-all text-xs">{value}</code>
        <button
          type="button"
          onClick={() => { void navigator.clipboard?.writeText(value); setOk(true); setTimeout(() => setOk(false), 1200); }}
          className="text-muted-foreground hover:text-foreground"
          aria-label="Copier"
        >
          {ok ? <Check className="size-4" /> : <Copy className="size-4" />}
        </button>
      </div>
    </div>
  );
}

export function Toggle({ checked, onChange, label, desc }: { checked: boolean; onChange: (v: boolean) => void; label: string; desc: string }) {
  return (
    <button
      type="button"
      role="switch"
      aria-checked={checked}
      onClick={() => onChange(!checked)}
      className={cn("flex w-full items-start gap-3 rounded-lg border p-3 text-left transition-colors", checked ? "border-primary bg-accent" : "hover:bg-accent/50")}
    >
      <span className={cn("mt-0.5 flex h-5 w-9 shrink-0 items-center rounded-full p-0.5 transition-colors", checked ? "bg-primary" : "bg-input")}>
        <span className={cn("size-4 rounded-full bg-background transition-transform", checked && "translate-x-4")} />
      </span>
      <span>
        <span className="block text-sm font-medium">{label}</span>
        <span className="block text-xs text-muted-foreground">{desc}</span>
      </span>
    </button>
  );
}

